//! Exports against hand-checked files and a sample-by-sample model.

use std::io::{Cursor, Read};

use hsync_capture::LogicCapture;
use hsync_core::ChannelIndex;
use hsync_fileio::{ExportFormat, ExportRequest, FileError, export};

/// A capture whose channels hold the given levels, one string of `0`/`1` each.
fn build(rate: u64, levels: &[(ChannelIndex, &str)]) -> LogicCapture {
    let mut capture = LogicCapture::new(rate, levels.iter().map(|(index, _)| *index));
    for (index, text) in levels {
        let bits: Vec<bool> = text.bytes().map(|b| b == b'1').collect();
        let words: Vec<u64> = bits
            .chunks(64)
            .map(|chunk| {
                chunk
                    .iter()
                    .enumerate()
                    .fold(0, |word, (bit, &high)| word | (u64::from(high) << bit))
            })
            .collect();
        let data = capture.channel_mut(*index).expect("channel");
        data.append_words(&words);
        data.truncate(bits.len() as u64);
    }
    capture
}

fn run(capture: &LogicCapture, format: ExportFormat, names: &[(ChannelIndex, String)]) -> Vec<u8> {
    let request = ExportRequest {
        format,
        channels: names,
        total_channels: 16,
        first_sample: 0,
        date: "2026-10-10 06:30:00 UTC",
        generator: "HSync 0.1.0",
    };
    export(Cursor::new(Vec::new()), capture, &request, &mut |_| true)
        .expect("export")
        .into_inner()
}

fn names(list: &[(ChannelIndex, &str)]) -> Vec<(ChannelIndex, String)> {
    list.iter()
        .map(|(index, name)| (*index, (*name).to_owned()))
        .collect()
}

#[test]
fn writes_dsviews_csv() {
    let capture = build(1_000_000, &[(0, "0011"), (2, "0101")]);
    let text = run(
        &capture,
        ExportFormat::Csv {
            every_sample: false,
        },
        &names(&[(0, "SDA"), (2, "SCL")]),
    );
    assert_eq!(
        String::from_utf8(text).expect("utf-8"),
        "; CSV, generated by HSync 0.1.0, sampled on 2026-10-10 06:30:00 UTC\n\
         ; Channels (2/16)\n\
         ; Sample rate: 1 MHz\n\
         ; Sample count: 4\n\
         Time(s), SDA, SCL\n\
         0,0,0\n\
         1e-06,0,1\n\
         2e-06,1,0\n\
         3e-06,1,1\n"
    );
    let every = run(
        &build(1_000_000, &[(0, "0000")]),
        ExportFormat::Csv { every_sample: true },
        &names(&[(0, "D0")]),
    );
    assert!(
        String::from_utf8(every)
            .expect("utf-8")
            .ends_with("0,0\n1e-06,0\n2e-06,0\n3e-06,0\n")
    );
}

#[test]
fn writes_value_changes() {
    let capture = build(25_000_000, &[(0, "0011"), (1, "1111")]);
    let text = run(
        &capture,
        ExportFormat::Vcd,
        &names(&[(0, "SDA"), (1, "SCL")]),
    );
    assert_eq!(
        String::from_utf8(text).expect("utf-8"),
        "$date 2026-10-10 06:30:00 UTC $end\n\
         $version HSync 0.1.0 $end\n\
         $comment\n  Acquisition with 2/16 channels at 25 MHz\n$end\n\
         $timescale 10 ns $end\n\
         $scope module HSync $end\n\
         $var wire 1 ! SDA $end\n\
         $var wire 1 \" SCL $end\n\
         $upscope $end\n$enddefinitions $end\n\
         #0 0! 1\"\n\
         #8 1!\n\
         #16\n"
    );
}

/// Sample `s` of channel `k` from the interleaved bytes.
fn bit(bytes: &[u8], unit: usize, sample: usize, channel: usize) -> bool {
    bytes[sample * unit + channel / 8] >> (channel % 8) & 1 != 0
}

#[test]
fn interleaves_any_number_of_channels() {
    let mut seed = 0x9e37_79b9_7f4a_7c15u64;
    let mut random = move || {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        seed
    };
    for count in [1usize, 3, 8, 9, 16, 17] {
        let texts: Vec<String> = (0..count)
            .map(|_| {
                (0..200)
                    .map(|_| if random() & 1 == 1 { '1' } else { '0' })
                    .collect()
            })
            .collect();
        let levels: Vec<(ChannelIndex, &str)> = texts
            .iter()
            .enumerate()
            .map(|(index, text)| (index as ChannelIndex * 2, text.as_str()))
            .collect();
        let capture = build(1_000, &levels);
        let list: Vec<(ChannelIndex, String)> = levels
            .iter()
            .map(|(index, _)| (*index, format!("D{index}")))
            .collect();
        let bytes = run(&capture, ExportFormat::Binary, &list);
        let unit = count.div_ceil(8);
        assert_eq!(bytes.len(), 200 * unit, "{count} channels");
        for (channel, text) in texts.iter().enumerate() {
            for (sample, level) in text.bytes().enumerate() {
                assert_eq!(
                    bit(&bytes, unit, sample, channel),
                    level == b'1',
                    "{count}/{channel}/{sample}"
                );
            }
        }
    }
}

#[test]
fn writes_a_sigrok_session() {
    let capture = build(25_000_000, &[(0, "0011"), (5, "0101")]);
    let list = names(&[(0, "SDA"), (5, "SCL")]);
    let archive = run(&capture, ExportFormat::Sigrok, &list);
    let mut zip = zip::ZipArchive::new(Cursor::new(archive)).expect("zip");
    let mut text = |name: &str| {
        let mut out = String::new();
        zip.by_name(name)
            .expect(name)
            .read_to_string(&mut out)
            .expect("read");
        out
    };
    assert_eq!(text("version"), "2");
    assert_eq!(
        text("metadata"),
        "[global]\nsigrok version=0.5.2\n\n[device 1]\ncapturefile=logic-1\ntotal probes=2\n\
         samplerate=25 MHz\ntotal analog=0\nprobe1=SDA\nprobe2=SCL\nunitsize=1\n"
    );
    let mut samples = Vec::new();
    zip.by_name("logic-1-1")
        .expect("chunk")
        .read_to_end(&mut samples)
        .expect("read");
    assert_eq!(samples, vec![0b00, 0b10, 0b01, 0b11]);
    assert_eq!(samples, run(&capture, ExportFormat::Binary, &list));
}

#[test]
fn stops_when_cancelled() {
    let capture = build(1_000, &[(0, "0101")]);
    let list = names(&[(0, "D0")]);
    let request = ExportRequest {
        format: ExportFormat::Binary,
        channels: &list,
        total_channels: 1,
        first_sample: 0,
        date: "",
        generator: "",
    };
    let result = export(Cursor::new(Vec::new()), &capture, &request, &mut |_| false);
    assert!(matches!(result, Err(FileError::Cancelled)));
}
